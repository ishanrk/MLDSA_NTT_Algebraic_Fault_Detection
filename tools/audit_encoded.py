#!/usr/bin/env python3
"""Exact field rank certificate for the included public encoded checker."""
import argparse
import json
import re
from pathlib import Path

from gen_encoded_tables import C, N, Q, R, emit, make, rank

ROOT = Path(__file__).resolve().parents[1]
SEED = 204256


def stage(a, number, zetas):
    a = a.copy()
    k = (1 << number) - 1
    length = N // (2 << number)
    for off in range(0, N, 2 * length):
        k += 1
        z = zetas[k]
        for i in range(off, off + length):
            t = z * a[i + length] % Q
            x = a[i]
            a[i] = (x + t) % Q
            a[i + length] = (x - t) % Q
    return a


def boundary_maps(number, h, u, zetas):
    # B maps a boundary error to the six final check syndromes.
    b = []
    for i in range(N):
        a = [0] * N
        a[i] = 1
        for s in range(number, 8):
            a = stage(a, s, zetas)
        b.append([sum(x * y for x, y in zip(row, a)) % Q for row in h])
    # X maps five fresh mask coordinates into this boundary's buffer.
    x = [[u[j][i] for j in range(R)] for i in range(N)]
    for s in range(number):
        x = list(zip(*(stage(list(col), s, zetas) for col in zip(*x))))
    return b, x


def audit():
    pi, w, u, h, v, zero_rank = make(SEED)
    invpi = [0] * N
    for i, value in enumerate(pi):
        invpi[value] = i
    generated = "// Generated by tools/gen_encoded_tables.py\n" + (
        f"// Public permutation seed {SEED}. Zero twiddle rank {zero_rank}.\n") + (
        "static const uint8_t enc_invpi[MLDSA_N] = {\n" +
        "\n".join("    " + ", ".join(str(x) for x in invpi[i:i + 16]) + ","
                  for i in range(0, N, 16)) + "\n};\n\n") + (
        "\n\n".join(emit(name, rows) for name, rows in
                      (("enc_h", h), ("enc_v", v))) + "\n")
    assert generated == (ROOT / "src/encoded_tables.inc").read_text(), "tables differ from generator"
    zetas = list(map(int, re.findall(r"\d+", (ROOT / "src/zetas.inc").read_text())))
    assert len(zetas) == N
    seen = set()
    singleton = 0
    short = 0
    long = 0
    for boundary in range(9):
        b, x = boundary_maps(boundary, h, u, zetas)
        if boundary == 0:
            assert all([b[i][k] for i in range(N)] == w[k] for k in range(C))
        if boundary == 8:
            assert all([x[i][j] for i in range(N)] == v[j] for j in range(R))
        for i in range(N):
            column = b[i]
            first = next((z for z in column if z), None)
            assert first is not None, (boundary, i, "zero column")
            inv = pow(first, Q - 2, Q)
            norm = tuple(z * inv % Q for z in column)
            assert norm not in seen, (boundary, i, "proportional column")
            seen.add(norm)
            singleton += 1
        for left in range(N):
            p = [[0] * R for _ in range(C)]
            total = [0] * C
            for right in range(left, N):
                for k in range(C):
                    total[k] = (total[k] + b[right][k]) % Q
                    for j in range(R):
                        p[k][j] = (p[k][j] + b[right][k] * x[right][j]) % Q
                length = right - left + 1
                if length <= C:
                    columns = [[b[i][k] for i in range(left, right + 1)]
                               for k in range(C)]
                    assert rank(columns) == length, (boundary, left, right, "short interval")
                    short += 1
                else:
                    assert rank(p) == R, (boundary, left, right, "zero interval")
                    assert rank([row + [total[k]] for k, row in enumerate(p)]) == C, (
                        boundary, left, right, "common overwrite")
                    long += 1
    assert zero_rank == R
    return {
        "q": Q, "n": N, "permutation_seed": SEED,
        "single_wire_locations": singleton,
        "pairs_of_distinct_wire_locations": singleton * (singleton - 1) // 2,
        "short_intervals_per_fault_type": short,
        "long_intervals_per_fault_type": long,
        "all_twiddles_zero_rank": zero_rank,
        "per_event_escape_bound": "q^-5",
        "catalog_union_bound_numerator": 2 * long + 1,
        "scope": "field arithmetic; one modeled event; protected checker and input",
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", type=Path)
    args = parser.parse_args()
    result = audit()
    if args.json:
        args.json.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
