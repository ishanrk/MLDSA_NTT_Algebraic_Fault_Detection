#!/usr/bin/env python3
"""Generate the public input mask and output check tables for the local demo."""
import math
import random
from pathlib import Path

Q = 8380417
N = 256
ROOT = 1753
R = 5
C = 6


def rev8(x):
    return int(f"{x:08b}"[::-1], 2)


roots = [pow(ROOT, 2 * rev8(j) + 1, Q) for j in range(N)]
inv_n = pow(N, Q - 2, Q)


def rank(rows):
    a = [list(row) for row in rows]
    lead = 0
    for col in range(len(a[0])):
        pivot = next((i for i in range(lead, len(a)) if a[i][col] % Q), None)
        if pivot is None:
            continue
        a[lead], a[pivot] = a[pivot], a[lead]
        inv = pow(a[lead][col], Q - 2, Q)
        a[lead] = [(v * inv) % Q for v in a[lead]]
        for i in range(lead + 1, len(a)):
            f = a[i][col]
            if f:
                a[i] = [(x - f * y) % Q for x, y in zip(a[i], a[lead])]
        lead += 1
        if lead == len(a):
            break
    return lead


def make(seed):
    pi = list(range(N))
    random.Random(seed).shuffle(pi)
    w = [[math.comb(pi[i], k) % Q for i in range(N)] for k in range(C)]
    u = [[math.comb(pi[i] + 1, j + 1) % Q for i in range(N)] for j in range(R)]
    h = [[0] * N for _ in range(C)]
    v = [[0] * N for _ in range(R)]
    for slot, root in enumerate(roots):
        x = pow(root, Q - 2, Q)
        power = inv_n
        for i in range(N):
            for k in range(C):
                h[k][slot] = (h[k][slot] + w[k][i] * power) % Q
            power = power * x % Q
        power = 1
        for i in range(N):
            for j in range(R):
                v[j][slot] = (v[j][slot] + u[j][i] * power) % Q
            power = power * root % Q
    # A zero-twiddle transform maps every input to its coefficient at index 0.
    syndrome = [[(sum(h[k]) * u[j][0] - sum(h[k][s] * v[j][s] for s in range(N))) % Q
                 for j in range(R)] for k in range(C)]
    return pi, w, u, h, v, rank(syndrome)


def emit(name, rows):
    lines = [f"static const uint32_t {name}[{len(rows)}][MLDSA_N] = {{"]
    for row in rows:
        lines.append("    {")
        for i in range(0, N, 8):
            lines.append("        " + ", ".join(str(x) + "U" for x in row[i:i + 8]) + ",")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines)


def main():
    seed = 204256
    pi, w, u, h, v, r = make(seed)
    assert r == R, f"zero twiddle rank was {r}"
    invpi = [0] * N
    for i, value in enumerate(pi):
        invpi[value] = i
    dest = Path(__file__).resolve().parents[1] / "src/encoded_tables.inc"
    dest.write_text("// Generated by tools/gen_encoded_tables.py\n"
                    f"// Public permutation seed {seed}. Zero twiddle rank {r}.\n"
                    + "static const uint8_t enc_invpi[MLDSA_N] = {\n"
                    + "\n".join("    " + ", ".join(str(x) for x in invpi[i:i + 16]) + ","
                                for i in range(0, N, 16)) + "\n};\n\n"
                    + "\n\n".join(emit(name, rows) for name, rows in
                                   (("enc_h", h), ("enc_v", v)))
                    + "\n")
    print(f"{dest}: zero twiddle rank {r}, permutation head {pi[:8]}")


if __name__ == "__main__":
    main()
